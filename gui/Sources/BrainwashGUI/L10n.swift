        let override = UserDefaults.standard.string(forKey: "brainwash.language") ?? "system"
        if override != "system", tables[override] != nil {
            return override
        }
        let langs = Locale.preferredLanguages
        let primary = langs.first ?? Locale.current.identifier
        let folded = primary.lowercased().replacingOccurrences(of: "_", with: "-")
        if folded.hasPrefix("zh-hant") || folded.hasPrefix("zh-tw") || folded.hasPrefix("zh-hk") || folded.hasPrefix("zh-mo") {
            return "zh-Hant"
        }
        if folded.hasPrefix("zh") {
            return "zh-Hans"
        }
        return "en"
    }

    static func t(_ key: String, _ args: Any...) -> String {
        let table = tables[language] ?? tables["en"]!
        var s = table[key] ?? tables["en"]?[key] ?? key
        for (i, arg) in args.enumerated() {
            s = s.replacingOccurrences(of: "{\(i)}", with: String(describing: arg))
        }
        return s
    }

